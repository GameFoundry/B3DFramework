. ./B3DBuildCommon.sh

echo "Builds NVIDIA PhysX 5 from source"
echo ""

# PhysX-specific CMake arguments per platform. PhysX selects its platform sources and output naming through
# TARGET_BUILD_PLATFORM rather than CMake's own platform detection.
if [[ "$Platform" == "win32" || "$Platform" == "msys" ]]; then
	# "-A" is specific to Visual Studio generators, and the release and checked builds below need a multi-config generator.
	# A single-config generator such as Ninja would ignore --config, so reject others rather than fail partway through.
	case "$CMakeGenerator" in
		"Visual Studio"*) ;;
		*)
			echo "[Error] Building PhysX on Windows requires a Visual Studio generator, but B3D_CMAKE_GENERATOR is '$CMakeGenerator'."
			exit 1
			;;
	esac

	PhysXPlatformArgs="-A x64 -DTARGET_BUILD_PLATFORM=windows -DPX_OUTPUT_ARCH=x86"
else
	echo "[Error] Building PhysX is not supported on platform '$Platform'."
	exit 1
fi

# Create intermediate folders
cd ..

mkdir -p Intermediate
cd Intermediate

mkdir -p DependencySources
cd DependencySources

# Pinned PhysX revision: SDK release 5.9.0, tag 110.1-omni-and-physx-5.9.0. Collision data cooked on the host must come
# from the same revision that the target platform links, so every platform builds this exact commit.
PHYSX_COMMIT="517a0073715120e114ee055b63b26c95e00d9039"

# The upstream repository carries a long history, so fetch only the pinned commit
if [ ! -d "PhysX5/.git" ]; then
	git init -q PhysX5 || exit 1
	git -C PhysX5 remote add origin https://github.com/NVIDIA-Omniverse/PhysX.git || exit 1
fi

cd PhysX5
if ! git cat-file -e "$PHYSX_COMMIT^{commit}" 2>/dev/null; then
	git fetch --depth 1 origin $PHYSX_COMMIT || exit 1
fi

# Forced checkout also reverts the patch applied by a previous run
git checkout -q --force $PHYSX_COMMIT || exit 1

PhysXRoot="$(pwd)/physx"

# Apply patch. PhysX's "checked" configuration uses the release CRT, while Banshee's Debug configuration (which maps to
# checked, see below) uses the debug CRT. The libraries are static, so the mismatch fails the link with LNK2038. The
# patch builds checked against the debug CRT with _DEBUG instead of NDEBUG, the same as PhysX's own debug configuration.
echo "Applying PhysX patch..."
git apply "$CurrentDirectory/Patches/PhysX.patch" || exit 1

# Setup output folders
OutputFolder="$PlatformDependencyFolder/PhysX"
B3DCleanDependencyFolder "$OutputFolder"
BuildFolder="${B3D_DEPENDENCY_BUILD_FOLDER:-build}"
PhysXOutputFolder="$(pwd)/$BuildFolder/output"

# Configure. CPU simulation only: no GPU projects, no OmniPVD runtime and no samples. All libraries are static, so
# consumers must define PX_PHYSX_STATIC_LIB and DISABLE_CUDA_PHYSX, see the bsfPhysX CMakeLists.txt.
cmake -S "$PhysXRoot/compiler/public" -B "$BuildFolder" -G "$CMakeGenerator" $PhysXPlatformArgs \
	-DPHYSX_ROOT_DIR="$PhysXRoot" \
	-DPX_OUTPUT_LIB_DIR="$PhysXOutputFolder" \
	-DPX_OUTPUT_BIN_DIR="$PhysXOutputFolder" \
	-DPX_GENERATE_STATIC_LIBRARIES=ON \
	-DPX_GENERATE_GPU_PROJECTS=OFF \
	-DPX_BUILDPVDRUNTIME=OFF \
	-DPX_BUILDSNIPPETS=OFF \
	-DNV_USE_STATIC_WINCRT=OFF \
	-DNV_USE_DEBUG_WINCRT=ON \
	$B3D_EXTRA_CMAKE_ARGS || exit 1

# Libraries consumed by the engine. The engine doesn't connect to PVD, but checked builds compile in PVD support and
# reference PhysXPvdSDK.
PhysXLibraries="PhysX PhysXCommon PhysXCooking PhysXFoundation PhysXExtensions PhysXCharacterKinematic PhysXPvdSDK"

# Banshee's Debug configuration maps to PhysX's "checked" configuration rather than PhysX "debug", which is too slow to
# be usable. Checked keeps optimizations on but adds runtime validation of API usage.
cmake --build "$BuildFolder" --config release --parallel --target $PhysXLibraries || exit 1
cmake --build "$BuildFolder" --config checked --parallel --target $PhysXLibraries || exit 1

# PhysX outputs into a folder named after the platform, compiler and CRT, e.g. bin/win.x86_64.vc143.md/<config>
for PlatformOutputFolder in "$PhysXOutputFolder"/bin/*; do
	break
done

# Helper: copies a static library, and its debug symbols if present, from a PhysX configuration folder
fnCopyLibrary() {
	local libraryName="$1"
	local sourceFolder="$2"
	local destinationFolder="$3"

	cp -p "$sourceFolder/${StaticLibraryPrefix}${libraryName}${StaticLibraryExtension}" "$destinationFolder/" || return 1
	if [ -f "$sourceFolder/${libraryName}.pdb" ]; then
		cp -p "$sourceFolder/${libraryName}.pdb" "$destinationFolder/" || return 1
	fi
}

mkdir -p "$OutputFolder/lib/Release"
mkdir -p "$OutputFolder/lib/Debug"

for LibraryName in $PhysXLibraries; do
	fnCopyLibrary "${LibraryName}_static_64" "$PlatformOutputFolder/release" "$OutputFolder/lib/Release" || exit 1
	fnCopyLibrary "${LibraryName}_static_64" "$PlatformOutputFolder/checked" "$OutputFolder/lib/Debug" || exit 1
done

# Public headers, including the PxConfig.h generated by the configure step
echo "Copying headers..."
mkdir -p "$OutputFolder/include"
cp -rp "$PhysXRoot/include/." "$OutputFolder/include/" || exit 1

# License file for redistribution
cp -p "$PhysXRoot/../LICENSE.md" "$OutputFolder/License.txt" || exit 1

B3DStampDependencyBuild "$OutputFolder"

echo ""
echo "======================================================================"
echo "Build complete!"
echo "======================================================================"
echo ""
echo "PhysX 5 has been built and installed to:"
echo "  $OutputFolder"
echo ""
